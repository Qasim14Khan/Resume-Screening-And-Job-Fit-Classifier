"""Write the trained model as a readable PYTHON file (no binary).

Run:  python export_model.py
Reads  models/resume_model.joblib
Writes models/resume_model_readable.py   (plain Python lists: categories, vocabulary, idf, weights, intercepts)

A trained Logistic Regression is just numbers: one weight per word per category. This file shows them.
Use predict_readable.py to make a prediction from this file alone (no scikit-learn, no joblib).
"""
import os

import joblib

PATH = "models/resume_model.joblib"
OUT = "models/resume_model_readable.py"
bundle = joblib.load(PATH)
model, le = bundle["model"], bundle["label_encoder"]
tfidf, clf = model.named_steps["tfidf"], model.named_steps["clf"]
if not hasattr(clf, "coef_"):
    raise SystemExit("This export works for Logistic Regression only (the deployed model).")

vocab = [t for t, _ in sorted(tfidf.vocabulary_.items(), key=lambda kv: kv[1])]


def nums(values, per_line=10, digits=6):
    items = [f"{float(v):.{digits}g}" for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "[\n    " + ",\n    ".join(lines) + ",\n]"


with open(OUT, "w", encoding="utf-8") as f:
    f.write('"""Trained resume classifier written as plain Python (generated by export_model.py).\n\n')
    f.write("Model: " + str(bundle["model_name"]) + "\n")
    f.write("How it predicts: score(category) = sum over words of  weight * tfidf(word)  +  intercept.\n")
    f.write(f"Then softmax turns the {len(le.classes_)} scores into probabilities. The highest probability is the prediction.\n")
    f.write("Each row of COEF is one category; each column is one word of VOCABULARY.\n")
    f.write('"""\n\n')
    f.write(f"NGRAM_RANGE = {tuple(tfidf.ngram_range)}\n")
    f.write(f"SUBLINEAR_TF = {bool(tfidf.sublinear_tf)}\n\n")
    f.write("CLASSES = " + repr([str(c) for c in le.classes_]) + "\n\n")
    f.write("INTERCEPT = " + nums(clf.intercept_, 8) + "\n\n")
    f.write("# one number per word: how rare the word is across all resumes (rare = bigger)\n")
    f.write("IDF = " + nums(tfidf.idf_) + "\n\n")
    f.write("# the words and two-word phrases the model knows (in column order)\n")
    words = [repr(w) for w in vocab]
    f.write("VOCABULARY = [\n" + "".join("    " + ", ".join(words[i:i + 6]) + ",\n" for i in range(0, len(words), 6)) + "]\n\n")
    f.write("# weights: COEF[category][word]. Positive = the word points TO this category.\n")
    f.write("COEF = [\n")
    for i, c in enumerate(le.classes_):
        f.write(f"    # ---- {c} ----\n    " + nums(clf.coef_[i]).replace("\n", "\n    ") + ",\n")
    f.write("]\n")
print(f"Wrote {OUT} ({os.path.getsize(OUT) / 1024:.0f} KB): {len(le.classes_)} categories x {len(vocab)} words")
